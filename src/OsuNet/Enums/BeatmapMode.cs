namespace OsuNet.Enums {
    /// <summary>
    /// Represents the available game modes in osu!.
    /// </summary>
    public enum BeatmapMode {
        /// <summary>
        /// osu!standard mode (Click the circles to the beat).
        /// </summary>
        Osu = 0,

        /// <summary>
        /// osu!taiko mode (Hit the drums to the beat).
        /// </summary>
        Taiko = 1,

        /// <summary>
        /// osu!catch mode (Catch the fruit to the beat).
        /// </summary>
        Catch = 2,

        /// <summary>
        /// osu!mania mode (Hit the notes to the beat).
        /// </summary>
        Mania = 3
    }
}
